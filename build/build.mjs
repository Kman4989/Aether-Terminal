const R = (p) => readFileSync(join(ROOT, p));
const RS = (p) => R(p).toString("utf8");
const b64 = (buf) => buf.toString("base64");

/** [filename] -> data URI (base64) */
const mimeOf = (p) => {
  if (p.endsWith(".svg")) return "image/svg+xml";
  if (p.endsWith(".png")) return "image/png";
  if (p.endsWith(".ico")) return "image/x-icon";
  if (p.endsWith(".woff2")) return "font/woff2";
  if (p.endsWith(".bin")) return "application/octet-stream";
  if (p.endsWith(".wasm")) return "application/wasm";
  return "application/octet-stream";
};
const dataUri = (p, base = ROOT) =>
  `data:${mimeOf(p)};base64,` + b64(readFileSync(join(base, p)));

const must = (cond, msg) => {
  if (!cond) throw new Error("BUILD FAILED: " + msg);
};
/** replace exactly once, verifying */
const rep = (src, from, to, tag) => {
  const i = src.indexOf(from);
  must(i >= 0, `pattern not found [${tag}]`);
  must(src.indexOf(from, i + 1) < 0 || from.length < 12, `pattern not unique [${tag}]`);
  return src.slice(0, i) + to + src.slice(i + from.length);
};
const repAll = (src, from, to, tag) => {
  must(src.includes(from), `pattern not found [${tag}]`);
  return src.split(from).join(to);
};
/** JSON-escape a string for embedding inside a <script> safely */
const jsStr = (s) => JSON.stringify(s).replace(/<\//g, "<\\/");

