/**
 * Aether-Terminal (NettleWeb) single-file builder.
 *
 * Packs the entire frontend into one self-contained HTML file:
 *  - index shell + full decrypted page markup (captured from the served bundle)
 *  - all CSS inlined (common/index/dark/player/jsdos/emulator) with assets as data URIs
 *  - main.js patched for single-file operation (no server paths, no origin lock)
 *  - hls.js + worker inlined; game emulator libraries served from the jsDelivr
 *    GitHub mirror of the upstream repository (exact same versions)
 *  - ext apps (calculator / console / webemu) and the game player embedded as
 *    runtime blob-URL documents
 */
